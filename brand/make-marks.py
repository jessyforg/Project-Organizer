"""Writes the Katha marks: the banig weave, a 3x3 over-under weave of blue and amber strips.

Each crossing is drawn as the strip that is on top there, a little longer along that strip and
narrower across it, so the cells read as woven rather than as a checkerboard. The 16 px files
use whole pixels so they stay sharp. Pure Python, no dependencies.

Usage, from the repository root (the wordmark embeds the app's font from node_modules):
    python brand/make-marks.py
"""
import base64
import pathlib

HERE = pathlib.Path(__file__).parent
FONT = HERE.parent / 'node_modules/@fontsource/atkinson-hyperlegible-next/files/atkinson-hyperlegible-next-latin-800-normal.woff2'

# Vertical strips, horizontal strips.
LIGHT = ('#3566c8', '#e39a2d')
DARK = ('#6f98e8', '#f0a948')
ON_TILE = ('#ffffff', '#f3ab4a')
TILE = '#2a5aa6'  # the app's --accent


def weave(origin, cell, gap, reach, inset, rx, colours, n=3):
    """The weave's rectangles, inside a square that starts at `origin`."""
    vertical, horizontal = colours
    pos = [origin + k * (cell + gap) for k in range(n)]
    lo, hi = origin, origin + n * cell + (n - 1) * gap
    rects = []
    for c in range(n):
        for r in range(n):
            x, y = pos[c], pos[r]
            if (c + r) % 2 == 0:  # the vertical strip is on top
                y0, y1 = max(lo, y - reach), min(hi, y + cell + reach)
                rects.append((x + inset, y0, cell - 2 * inset, y1 - y0, vertical))
            else:  # the horizontal strip is on top
                x0, x1 = max(lo, x - reach), min(hi, x + cell + reach)
                rects.append((x0, y + inset, x1 - x0, cell - 2 * inset, horizontal))
    return [
        f'<rect x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}" rx="{rx:g}" fill="{fill}"/>'
        for x, y, w, h, fill in rects
    ]


def write(name, size, note, body, tile_rx=None, extra=''):
    lines = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size[0]} {size[1]}">',
             '  <title>Katha</title>', f'  <!-- {note} Generated by make-marks.py. -->']
    if extra:
        lines.append('  ' + extra)
    if tile_rx is not None:
        lines.append(f'  <rect width="{size[0]}" height="{size[1]}" rx="{tile_rx:g}" fill="{TILE}"/>')
    lines += ['  ' + b for b in body] + ['</svg>']
    # newline='\n' keeps LF line endings on Windows too (.gitattributes: eol=lf).
    with open(HERE / name, 'w', encoding='utf-8', newline='\n') as out:
        out.write('\n'.join(lines) + '\n')


# The symbol on a 64-unit grid, and on whole pixels for 16 px.
MARK = dict(origin=6, cell=16, gap=2, reach=2, inset=3, rx=3)
MARK_16 = dict(origin=0, cell=5, gap=0.5, reach=0, inset=1, rx=0.75)

write('katha-mark.svg', (64, 64), 'For light backgrounds.', weave(colours=LIGHT, **MARK))
write('katha-mark-dark.svg', (64, 64), 'For dark backgrounds.', weave(colours=DARK, **MARK))
write('katha-mark-16.svg', (16, 16), 'Drawn for 16 px, on whole pixels.', weave(colours=LIGHT, **MARK_16))
write('katha-mark-mono.svg', (64, 64), 'One colour (currentColor).',
      weave(colours=('currentColor', 'currentColor'), **MARK))

# App icon tiles, one per icon size, so every edge falls on a whole pixel: a weave cell is a
# whole number of pixels and each bar is a whole number of pixels wide (about half a cell).
# The 48 grid file serves 48 px and up.
for size, cell, name in ((16, 4, 'katha-tile-16.svg'), (24, 6, 'katha-tile-24.svg'),
                         (32, 8, 'katha-tile-32.svg'), (48, 12, 'katha-tile.svg')):
    origin = (size - 3 * cell) // 2
    note = f'App icon at {size} px.' if size < 48 else 'App icon, 48 px and up.'
    write(name, (size, size), note,
          weave(colours=ON_TILE, origin=origin, cell=cell, gap=0, reach=0, inset=cell // 4, rx=cell / 8),
          tile_rx=size * 0.22)

# The wordmark: the symbol plus the name in Atkinson Hyperlegible Next ExtraBold, embedded
# (SIL Open Font License 1.1 permits embedding) so it renders the same everywhere.
font = base64.b64encode(FONT.read_bytes()).decode('ascii')
face = ('<style>@font-face{font-family:"Katha Wordmark";font-weight:800;'
        f'src:url(data:font/woff2;base64,{font}) format("woff2")}}</style>')
for name, colours, ink in (('katha-wordmark.svg', LIGHT, '#171b21'), ('katha-wordmark-dark.svg', DARK, '#e6e9ee')):
    text = (f'<text x="72" y="47" fill="{ink}" font-family="\'Katha Wordmark\', \'Atkinson Hyperlegible Next\', '
            '\'Segoe UI\', sans-serif" font-weight="800" font-size="44" letter-spacing="-0.9">Katha</text>')
    write(name, (234, 64), 'Wordmark. Font: Atkinson Hyperlegible Next ExtraBold, SIL OFL 1.1.',
          weave(colours=colours, **MARK) + [text], extra=face)
